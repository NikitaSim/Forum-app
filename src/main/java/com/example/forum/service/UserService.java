package com.example.forum.service;

import com.example.forum.models.User;
import com.example.forum.models.UserRole;
import com.example.forum.repository.UserRepository;
import com.example.forum.repository.ThreadRepository;
import com.example.forum.repository.PostRepository;
import com.example.forum.repository.CommentRepository;
import com.example.forum.exception.UserNotFoundException;
import com.example.forum.exception.InvalidRequestException;
import com.example.forum.exception.DuplicateResourceException;
import com.example.forum.exception.UserHasDependenciesException;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;
import java.util.Locale;

@Slf4j
@Service
//@RequiredArgsConstructor
@Transactional
public class UserService {
    private final UserRepository repository;
    private final PasswordEncoder passwordEncoder;
    private final ThreadRepository threads;
    private final PostRepository posts;
    private final CommentRepository comments;

    public UserService(PasswordEncoder passwordEncoder, UserRepository repository,
                       ThreadRepository threads, PostRepository posts, CommentRepository comments) {
        this.passwordEncoder = passwordEncoder;
        this.repository = repository;
        this.threads = threads;
        this.posts = posts;
        this.comments = comments;
    }

    public User create(User user) {
        validateUser(user);
        String username = user.getUsername().trim();
        String email = user.getEmail().trim().toLowerCase(Locale.ROOT);

        if (repository.existsByUsername(username)) {
            throw new DuplicateResourceException("Имя пользователя уже занято. Укажите другое имя.");
        }
        if (repository.existsByEmail(email)) {
            throw new DuplicateResourceException("Пользователь с таким email уже существует. Укажите другой адрес.");
        }

        user.setId(null); // ID is generated by PostgreSQL.
        user.setUsername(username);
        user.setEmail(email);
        user.setPassword(passwordEncoder.encode(user.getPassword()));
        if (user.getRole() == null) {
            user.setRole(UserRole.USER);
        }
        User saved = repository.save(user);
        log.info("Создан пользователь '{}' с ролью {}", saved.getUsername(), saved.getRole());
        return saved;
    }

    @Transactional(readOnly = true)
    public List<User> findAll() {
        return repository.findAll();
    }

    @Transactional(readOnly = true)
    public User find(Long id) {
        if (id == null || id <= 0) {
            throw new InvalidRequestException("ID пользователя должен быть положительным числом.");
        }
        return repository.findById(id)
                .orElseThrow(() -> new UserNotFoundException(id));
    }

    public User update(Long id, User input) {
        validateUserForUpdate(input);
        User user = find(id);

        String username = input.getUsername().trim();
        String email = input.getEmail().trim().toLowerCase(Locale.ROOT);

        repository.findByUsernameIgnoreCase(username)
                .filter(existing -> !existing.getId().equals(id))
                .ifPresent(existing -> {
                    throw new DuplicateResourceException("Имя пользователя уже занято. Укажите другое имя.");
                });

        if (repository.existsByEmail(email) && !email.equalsIgnoreCase(user.getEmail())) {
            throw new DuplicateResourceException("Пользователь с таким email уже существует. Укажите другой адрес.");
        }

        user.setUsername(username);
        user.setEmail(email);
        if (input.getRole() != null) {
            user.setRole(input.getRole());
        }
        if (input.getPassword() != null && !input.getPassword().isBlank()) {
            user.setPassword(passwordEncoder.encode(input.getPassword()));
        }
        return repository.save(user);
    }

    public void delete(Long id) {
        User user = find(id);
        long threadCount = threads.countByAuthorId(id);
        long postCount = posts.countByAuthorId(id);
        long commentCount = comments.countByAuthorId(id);

        if (threadCount > 0 || postCount > 0 || commentCount > 0) {
            throw new UserHasDependenciesException(id, threadCount, postCount, commentCount);
        }

        repository.delete(user);
        log.info("Удалён пользователь id={}", id);
    }

    private void validateUser(User user) {
        if (user == null) {
            throw new InvalidRequestException("Необходимо передать данные пользователя.");
        }
        validateUserForUpdate(user);
        if (user.getPassword() == null || user.getPassword().isBlank()) {
            throw new InvalidRequestException("Пароль обязателен.");
        }
        if (user.getPassword().length() < 6) {
            throw new InvalidRequestException("Пароль должен содержать не менее 6 символов.");
        }
    }

    private void validateUserForUpdate(User user) {
        if (user == null) {
            throw new InvalidRequestException("Необходимо передать данные пользователя.");
        }
        if (user.getUsername() == null || user.getUsername().isBlank()) {
            throw new InvalidRequestException("Имя пользователя обязательно.");
        }
        if (user.getUsername().trim().length() > 32) {
            throw new InvalidRequestException("Имя пользователя не должно превышать 32 символа.");
        }
        if (user.getEmail() == null || user.getEmail().isBlank() || !user.getEmail().contains("@")) {
            throw new InvalidRequestException("Укажите корректный адрес электронной почты.");
        }
    }
}
